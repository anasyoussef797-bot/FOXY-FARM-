export const LEVEL_EXP_TABLE = [
  0,     // Level 1
  100,   // Level 2
  250,   // Level 3
  450,   // Level 4
  700,   // Level 5 (Unlocks Chickens & Learning Center)
  1050,  // Level 6 (Unlocks Cotton & Greenhouse)
  1500,  // Level 7 (Unlocks Sunflowers & Spark Tech Lab)
  2100,  // Level 8 (Unlocks Horse & Foxy Clubhouse)
  2800,  // Level 9 (Unlocks Giant Pumpkin)
  3600,  // Level 10 (Master Explorer)
  4600,  // Level 11
  5800,  // Level 12
  7200,  // Level 13
  8800,  // Level 14
  10600, // Level 15 (Land Expansion Zone 3)
];

export function getLevelFromXP(xp: number): { level: number; currentLevelXP: number; nextLevelXP: number; progressPercent: number } {
  let level = 1;
  for (let i = 0; i < LEVEL_EXP_TABLE.length; i++) {
    if (xp >= LEVEL_EXP_TABLE[i]) {
      level = i + 1;
    } else {
      break;
    }
  }

  const prevXP = LEVEL_EXP_TABLE[level - 1] || 0;
  const nextXP = LEVEL_EXP_TABLE[level] || prevXP + 1500;
  const currentLevelXP = Math.max(0, xp - prevXP);
  const neededXP = nextXP - prevXP;
  const progressPercent = Math.min(100, Math.round((currentLevelXP / neededXP) * 100));

  return { level, currentLevelXP, nextLevelXP: neededXP, progressPercent };
}
